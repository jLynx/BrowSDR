/*
 * POCSAG codepages (7-bit, 128 codes) — RX decode (primary display glyph).
 *
 * POCSAG_TABLES holds one glyph table per unique codepage. POCSAG_CHARSETS
 * lists the selectable identities { vendor, model, codepage } — several share
 * one table (alias pager models), referenced by tableId so no table data is
 * duplicated. Tables are expressed as overrides on the standard ASCII identity
 * base (0x20..0x7E + CR/LF); an override of null unmaps a code that is
 * printable in the base.
 */

import type { CharsetTables, Codepage } from './types';

/** Standard ASCII identity base: 0x20..0x7E printable, plus LF (0x0A) / CR (0x0D). */
function asciiBase(): Codepage {
	const t = new Array<string | null>(128).fill(null);
	for (let c = 0x20; c <= 0x7e; c++) t[c] = String.fromCharCode(c);
	t[0x0a] = '\n';
	t[0x0d] = '\r';
	return t;
}

/** Apply sparse code→glyph overrides onto a fresh ASCII base. */
function withOverrides(overrides: Record<number, string | null>): Codepage {
	const t = asciiBase();
	for (const k of Object.keys(overrides)) t[Number(k)] = overrides[Number(k)];
	return t;
}

