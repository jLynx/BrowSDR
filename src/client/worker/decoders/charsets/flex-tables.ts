/*
 * FLEX codepages (7-bit, 128 codes) -- RX decode (primary display glyph).
 *
 * Ported from osmocom-analog src/libpagercharset/charset_flex_*.c (entry[0],
 * the RX primary glyph; TX aliases are not needed for a receive-only decoder).
 * Expressed as overrides on the standard ASCII identity base (0x20-0x7E + CR/LF);
 * the Motorola Linguist sets remap the 0x01-0x1F control region to symbols and
 * add accented/script letters. An override of null unmaps a base-printable code.
 */

import type { CharsetTables, Codepage } from './types';

function asciiBase(): Codepage {
	const t = new Array<string | null>(128).fill(null);
	for (let c = 0x20; c <= 0x7e; c++) t[c] = String.fromCharCode(c);
	t[0x0a] = '\n';
	t[0x0d] = '\r';
	return t;
}

function withOverrides(overrides: Record<number, string | null>): Codepage {
	const t = asciiBase();
	for (const k of Object.keys(overrides)) t[Number(k)] = overrides[Number(k)];
	return t;
}

